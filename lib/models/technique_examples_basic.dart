/// 填数类技巧的标记：目标格涂 pattern 色，填入的候选涂 start 色。
BoardMarkup _fillMarkup(int r, int c, int value) => BoardMarkup(
      cellColors: {_ck(r, c): TeachingColors.pattern},
      candidateColors: {_cr(r, c, value): TeachingColors.start},
    );

/// 删除类技巧的标记：参与数组/区块的格子涂 pattern 色，被删掉的候选涂 elimCand 色。
BoardMarkup _elimMarkup(
  List<List<int>> patternCells,
  List<List<int>> eliminated,
) =>
    BoardMarkup(
      cellColors: {
        for (final cell in patternCells)
          _ck(cell[0], cell[1]): TeachingColors.pattern,
      },
      candidateColors: {
        for (final e in eliminated)
          _cr(e[0], e[1], e[2]): TeachingColors.elimCand,
      },
    );

