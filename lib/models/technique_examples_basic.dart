int _ck(int r, int c) => BoardMarkup.cellKey(r, c);
CandidateRef _cr(int r, int c, int n) => CandidateRef(r, c, n);

const _fillLegend = [
  TechniqueLegendItem(color: TeachingColors.pattern, label: '参与格'),
  TechniqueLegendItem(color: TeachingColors.start, label: '填入'),
];

const _elimLegend = [
  TechniqueLegendItem(color: TeachingColors.pattern, label: '数组/区块格'),
  TechniqueLegendItem(color: TeachingColors.elimCand, label: '删除'),
